/** The waves of the swing mode of the "Fan" key, drawn in a 24×24 box like the images of the manifest. */
export function swingGlyph(color: string): string {
	return `<g fill="none" stroke="${color}" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><path d="M3 8c3-3 6 3 9 0s6 3 9 0M3 16c3-3 6 3 9 0s6 3 9 0"/></g>`;
}
